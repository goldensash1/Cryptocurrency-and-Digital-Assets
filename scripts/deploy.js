const hre = require("hardhat");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

// SHA-256 of the real logo file, computed at deploy time.
function logoHash() {
  const file = fs.readFileSync(path.join(__dirname, "..", "alu-logo.png"));
  return "0x" + crypto.createHash("sha256").update(file).digest("hex");
}

// Read an ABI out of the Hardhat build output so the frontend always matches the contract.
async function abiOf(name) {
  return (await hre.artifacts.readArtifact(name)).abi;
}

async function main() {
  const signers = await hre.ethers.getSigners();
  const deployer = signers[0];
  const { chainId } = await hre.ethers.provider.getNetwork();
  console.log("Deploying with account:", deployer.address, "on chain", chainId.toString());

  // 1. ERC-721 registry, then register the logo straight away.
  const registry = await hre.ethers.deployContract("ALUAssetRegistry");
  await registry.waitForDeployment();
  console.log("ALUAssetRegistry deployed to:", await registry.getAddress());

  const hash = logoHash();
  const tx = await registry.registerAsset("ALU Official Logo", "image/png", hash);
  await tx.wait();
  console.log("ALU logo registered as token ID 1");
  console.log("SHA-256 content hash:", hash);

  // 2. ERC-20 share token; the deployer is the logo owner and gets all 1,000,000 ALUT.
  const token = await hre.ethers.deployContract("ALULogoToken", [deployer.address]);
  await token.waitForDeployment();
  console.log("ALULogoToken deployed to:", await token.getAddress());

  // 3. Example stakeholders so the dashboard has something to show.
  //    On the local chain we use Hardhat accounts #1-#3 with demo shares.
  //    On a public testnet these are fixed demo addresses and are NOT funded
  //    (the dashboard still lists them, with a zero balance until shares are sent).
  const isLocal = chainId === 31337n;
  const holders = isLocal
    ? [
        { label: "ALU Faculty Board", address: signers[1].address, shares: 250000 },
        { label: "Student Council", address: signers[2].address, shares: 150000 },
        { label: "ALU Alumni Fund", address: signers[3].address, shares: 100000 },
      ]
    : [
        { label: "ALU Faculty Board", address: "0x70997970C51812dc3A010C7d01b50e0d17dc79C8", shares: 0 },
        { label: "Student Council", address: "0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC", shares: 0 },
        { label: "ALU Alumni Fund", address: "0x90F79bf6EB2c4f870365E785982E1f101E93b906", shares: 0 },
      ];
  if (isLocal) {
    for (const h of holders) {
      await (await token.distributeShares(h.address, h.shares)).wait();
      console.log(`Sent ${h.shares} ALUT to ${h.label} (${h.address})`);
    }
  }
  console.log("Owner ALUT balance:", (await token.balanceOf(deployer.address)).toString());

  // 4. Write everything the frontend needs (addresses + ABIs + network).
  //    Skipped for the throwaway in-process "hardhat" network, which disappears when the script ends.
  if (hre.network.name === "hardhat") {
    console.log("In-process network: frontend/js/deployment.js not updated (use --network localhost or sepolia).");
    return;
  }
  const rpcUrl = isLocal ? "http://127.0.0.1:8545" : hre.network.config.url;
  const deployment = {
    network: { name: isLocal ? "Hardhat Local" : hre.network.name, chainId: Number(chainId), rpcUrl },
    registryAddress: await registry.getAddress(),
    tokenAddress: await token.getAddress(),
    deployBlock: (await registry.deploymentTransaction().wait()).blockNumber,
    logoTokenId: 1,
    logoHash: hash,
    holders: holders.map(({ label, address }) => ({ label, address })),
    registryAbi: await abiOf("ALUAssetRegistry"),
    tokenAbi: await abiOf("ALULogoToken"),
  };
  const out = path.join(__dirname, "..", "frontend", "js", "deployment.js");
  fs.writeFileSync(
    out,
    "// Generated by scripts/deploy.js - do not edit by hand.\nwindow.ALU_DEPLOYMENT = " +
      JSON.stringify(deployment, null, 2) +
      ";\n"
  );
  console.log("Frontend config written to frontend/js/deployment.js");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
